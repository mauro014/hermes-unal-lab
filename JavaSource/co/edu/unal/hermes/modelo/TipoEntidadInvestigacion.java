package co.edu.unal.hermes.modelo;

public class TipoEntidadInvestigacion{
    
  
    
	private Long id;
	private String nombre;
	private String nombreLoad;
	
	public String getNombre() {
		return nombre;
	}
	public void setNombre(String nombre) {
		this.nombre = nombre;
	}
	public Long getId() {
		return id;
	}
	public void setId(Long id) {
		this.id = id;
	}
	public String getNombreLoad() {
		return nombreLoad;
	}
	public void setNombreLoad(String nombreLoad) {
		this.nombreLoad = nombreLoad;
	}	
	
	
	
  
}
