package co.edu.unal.hermes.modelo;

public class ConvenioEstados {
	private String id;
	private String convenio;
	private String estado;
	private String fecest;	
	private String observaciones;	
	private String compromisos;
	
	public String getId() {
		return id;
	}
	public void setId(String id) {
		this.id = id;
	}
	public String getConvenio() {
		return convenio;
	}
	public void setConvenio(String convenio) {
		this.convenio = convenio;
	}
	public String getEstado() {
		return estado;
	}
	public void setEstado(String estado) {
		this.estado = estado;
	}
	public String getFecest() {
		return fecest;
	}
	public void setFecest(String fecest) {
		this.fecest = fecest;
	}
	public String getObservaciones() {
		return observaciones;
	}
	public void setObservaciones(String observaciones) {
		this.observaciones = observaciones;
	}
	public String getCompromisos() {
		return compromisos;
	}
	public void setCompromisos(String compromisos) {
		this.compromisos = compromisos;
	}

}
