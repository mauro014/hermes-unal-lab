package co.edu.unal.hermes.modelo;


public class CoordinadorAsesor  {
	
	private String dpnId;
	private String perId;
	private String tdoId;
	private String coorID;
	private String coorTpoId;
	
	public String getDpnId() {
		return dpnId;
	}
	public void setDpnId(String dpnId) {
		this.dpnId = dpnId;
	}
	public String getPerId() {
		return perId;
	}
	public void setPerId(String perId) {
		this.perId = perId;
	}
	public String getTdoId() {
		return tdoId;
	}
	public void setTdoId(String tdoId) {
		this.tdoId = tdoId;
	}
	public String getCoorID() {
		return coorID;
	}
	public void setCoorID(String coorID) {
		this.coorID = coorID;
	}
	public String getCoorTpoId() {
		return coorTpoId;
	}
	public void setCoorTpoId(String coorTpoId) {
		this.coorTpoId = coorTpoId;
	}
    
   
}
