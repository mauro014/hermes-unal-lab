package co.edu.unal.hermes.modelo;

public class SemilleroLaboratorioVista {

	private String id;
	private String nombre;
	private String lider;
	private String estado;
	private String sede;
	private String facultad;
	private String areaOCDEPrincipal;
	private String areasOCDESecundarias;
	private String estudiantesPregrado;
	private String estudiantesPosgrado;
	private String estudiantesLideres;
	private String estudiantesVisitantes;
	private String docentes;
	private String egresados;
	private String externos;
	
	public SemilleroLaboratorioVista() {
	}

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getNombre() {
		return nombre;
	}

	public void setNombre(String nombre) {
		this.nombre = nombre;
	}

	public String getLider() {
		return lider;
	}

	public void setLider(String lider) {
		this.lider = lider;
	}

	public String getEstado() {
		return estado;
	}

	public void setEstado(String estado) {
		this.estado = estado;
	}

	public String getSede() {
		return sede;
	}

	public void setSede(String sede) {
		this.sede = sede;
	}

	public String getFacultad() {
		return facultad;
	}

	public void setFacultad(String facultad) {
		this.facultad = facultad;
	}

	public String getAreaOCDEPrincipal() {
		return areaOCDEPrincipal;
	}

	public void setAreaOCDEPrincipal(String areaOCDEPrincipal) {
		this.areaOCDEPrincipal = areaOCDEPrincipal;
	}

	public String getAreasOCDESecundarias() {
		return areasOCDESecundarias;
	}

	public void setAreasOCDESecundarias(String areasOCDESecundarias) {
		this.areasOCDESecundarias = areasOCDESecundarias;
	}

	public String getEstudiantesPregrado() {
		return estudiantesPregrado;
	}

	public void setEstudiantesPregrado(String estudiantesPregrado) {
		this.estudiantesPregrado = estudiantesPregrado;
	}

	public String getEstudiantesPosgrado() {
		return estudiantesPosgrado;
	}

	public void setEstudiantesPosgrado(String estudiantesPosgrado) {
		this.estudiantesPosgrado = estudiantesPosgrado;
	}

	public String getEstudiantesLideres() {
		return estudiantesLideres;
	}

	public void setEstudiantesLideres(String estudiantesLideres) {
		this.estudiantesLideres = estudiantesLideres;
	}

	public String getEstudiantesVisitantes() {
		return estudiantesVisitantes;
	}

	public void setEstudiantesVisitantes(String estudiantesVisitantes) {
		this.estudiantesVisitantes = estudiantesVisitantes;
	}

	public String getDocentes() {
		return docentes;
	}

	public void setDocentes(String docentes) {
		this.docentes = docentes;
	}

	public String getEgresados() {
		return egresados;
	}

	public void setEgresados(String egresados) {
		this.egresados = egresados;
	}

	public String getExternos() {
		return externos;
	}

	public void setExternos(String externos) {
		this.externos = externos;
	}

}
